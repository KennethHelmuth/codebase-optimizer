import ast
import hashlib
import os
from collections import defaultdict
from typing import Dict, List, Optional, Set, Tuple


class ASTNormalizer(ast.NodeTransformer):
    """
    Normalizes an AST subtree by stripping docstrings, variable names,
    argument names, and literal values so structurally identical logic
    hashes to the exact same fingerprint.
    """

    def visit_FunctionDef(self, node: ast.FunctionDef) -> ast.AST:
        node.name = "FUNC"
        node.decorator_list = []
        node.returns = None
        if (
            node.body
            and isinstance(node.body[0], ast.Expr)
            and isinstance(node.body[0].value, ast.Constant)
            and isinstance(node.body[0].value.value, str)
        ):
            node.body = node.body[1:]
        self.generic_visit(node)
        return node

    def visit_AsyncFunctionDef(self, node: ast.AsyncFunctionDef) -> ast.AST:
        node.name = "ASYNC_FUNC"
        node.decorator_list = []
        node.returns = None
        if (
            node.body
            and isinstance(node.body[0], ast.Expr)
            and isinstance(node.body[0].value, ast.Constant)
            and isinstance(node.body[0].value.value, str)
        ):
            node.body = node.body[1:]
        self.generic_visit(node)
        return node

    def visit_arg(self, node: ast.arg) -> ast.AST:
        node.arg = "ARG"
        node.annotation = None
        return node

    def visit_Name(self, node: ast.Name) -> ast.AST:
        # Preserve builtin calls/types if common, normalize local identifiers
        builtins = {"len", "range", "print", "str", "int", "float", "list", "dict", "set", "tuple", "open", "isinstance", "Exception", "ValueError", "TypeError"}
        if node.id not in builtins:
            node.id = "VAR"
        return node

    def visit_Constant(self, node: ast.Constant) -> ast.AST:
        if isinstance(node.value, str):
            node.value = "STR"
        elif isinstance(node.value, (int, float)):
            node.value = 0
        return node


class SlopAuditor:
    """
    Phase 2: Anti-AI-Slop & Clone Auditor.
    Detects structural duplicate functions across files, cross-file dead exports,
    and hollow pass-through wrapper functions generated by AI agents.
    """

    IGNORE_DIRS = {
        ".git", "__pycache__", "venv", ".venv", "env",
        "node_modules", "build", "dist", ".pytest_cache", ".mypy_cache", "tests"
    }

    ENTRYPOINT_FILES = {
        "main.py", "app.py", "server.py", "mcp_server.py", "cli.py",
        "setup.py", "conftest.py", "manage.py", "__init__.py", "__main__.py"
    }

    @classmethod
    def _iter_python_files(cls, root_dir: str) -> List[Tuple[str, str, ast.Module]]:
        """Yields (rel_path, raw_code, ast_tree) for all valid Python files."""
        results = []
        for dirpath, dirnames, filenames in os.walk(root_dir):
            dirnames[:] = [d for d in sorted(dirnames) if d not in cls.IGNORE_DIRS]
            for fname in sorted(filenames):
                if not fname.endswith(".py"):
                    continue
                full_path = os.path.join(dirpath, fname)
                rel_path = os.path.relpath(full_path, root_dir)
                try:
                    with open(full_path, "r", encoding="utf-8") as f:
                        code = f.read()
                    tree = ast.parse(code, filename=rel_path)
                    results.append((rel_path, code, tree))
                except Exception:
                    continue
        return results

    @classmethod
    def find_duplicate_logic(cls, root_dir: str, min_lines: int = 5) -> List[Dict[str, object]]:
        """
        2.1 Structural AST Clone Detector:
        Hashes normalized AST subtrees of functions across the codebase to find
        Type-1 and Type-2 clones (identical logic even with renamed variables).
        """
        hash_buckets: Dict[str, List[Dict[str, object]]] = defaultdict(list)

        for rel_path, _, tree in cls._iter_python_files(root_dir):
            for node in ast.walk(tree):
                if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    start_line = getattr(node, "lineno", 1)
                    end_line = getattr(node, "end_lineno", start_line)
                    line_span = end_line - start_line + 1

                    if line_span < min_lines or node.name.startswith("__"):
                        continue

                    # Deep copy via parse/unparse before normalizing
                    try:
                        cloned_node = ast.parse(ast.unparse(node)).body[0]
                        normalized = ASTNormalizer().visit(cloned_node)
                        ast_dump = ast.dump(normalized, annotate_fields=True, include_attributes=False)
                        fingerprint = hashlib.sha256(ast_dump.encode("utf-8")).hexdigest()[:12]

                        hash_buckets[fingerprint].append({
                            "file": rel_path,
                            "function": node.name,
                            "lines": f"L{start_line}-L{end_line}",
                            "span": line_span,
                        })
                    except Exception:
                        continue

        clones = []
        for fp, occurrences in hash_buckets.items():
            if len(occurrences) > 1:
                clones.append({
                    "fingerprint": fp,
                    "count": len(occurrences),
                    "locations": occurrences,
                })
        return clones

    @classmethod
    def find_dead_exports(cls, root_dir: str) -> Dict[str, List[Dict[str, str]]]:
        """
        2.2 Cross-File Dead Export Hunter:
        Builds a full AST symbol definition vs. cross-file reference graph.
        Ignores framework entrypoints, decorator-registered routes/tools, and dunder methods.
        """
        files_data = cls._iter_python_files(root_dir)

        # Map: (rel_path, symbol_name) -> line_number
        definitions: Dict[str, List[Tuple[str, int, str]]] = defaultdict(list)
        # Map: symbol_name -> set of files where it is referenced
        references_by_symbol: Dict[str, Set[str]] = defaultdict(set)

        for rel_path, _, tree in files_data:
            fname = os.path.basename(rel_path)

            # Collect references across all AST nodes in this file
            for node in ast.walk(tree):
                if isinstance(node, ast.Name):
                    references_by_symbol[node.id].add(rel_path)
                elif isinstance(node, ast.Attribute):
                    references_by_symbol[node.attr].add(rel_path)
                elif isinstance(node, ast.alias):
                    references_by_symbol[node.name.split(".")[0]].add(rel_path)
                    if node.asname:
                        references_by_symbol[node.asname].add(rel_path)

            # Skip entrypoint modules when flagging dead definitions
            if fname in cls.ENTRYPOINT_FILES or fname.startswith("test_"):
                continue

            for node in tree.body:
                if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                    if node.name.startswith("_"):
                        continue
                    # Skip functions registered with framework decorators (e.g., @app.route, @mcp.tool)
                    if node.decorator_list:
                        continue
                    kind = "class" if isinstance(node, ast.ClassDef) else "function"
                    definitions[rel_path].append((node.name, node.lineno, kind))

        dead_by_file: Dict[str, List[Dict[str, str]]] = {}
        for rel_path, defs in definitions.items():
            dead_list = []
            for sym_name, lineno, kind in defs:
                ref_files = references_by_symbol.get(sym_name, set())
                external_refs = ref_files - {rel_path}
                if not external_refs:
                    dead_list.append({
                        "symbol": sym_name,
                        "kind": kind,
                        "line": f"L{lineno}",
                    })
            if dead_list:
                dead_by_file[rel_path] = dead_list

        return dead_by_file

    @classmethod
    def find_useless_wrappers(cls, root_dir: str) -> List[Dict[str, str]]:
        """
        2.3 Pass-Through Wrapper Detector:
        Detects hollow single-statement wrapper functions that immediately return
        a call to another function forwarding the exact same arguments without transformation.
        """
        wrappers = []

        for rel_path, _, tree in cls._iter_python_files(root_dir):
            for node in ast.walk(tree):
                if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    continue
                if node.decorator_list or node.name.startswith("_"):
                    continue

                # Strip leading docstring from body
                body = list(node.body)
                if (
                    body
                    and isinstance(body[0], ast.Expr)
                    and isinstance(body[0].value, ast.Constant)
                    and isinstance(body[0].value.value, str)
                ):
                    body = body[1:]

                if len(body) != 1:
                    continue

                stmt = body[0]
                call_node = None
                if isinstance(stmt, ast.Return) and isinstance(stmt.value, ast.Call):
                    call_node = stmt.value
                elif isinstance(stmt, ast.Expr) and isinstance(stmt.value, ast.Call):
                    call_node = stmt.value
                elif isinstance(stmt, ast.Return) and isinstance(stmt.value, ast.Await) and isinstance(stmt.value.value, ast.Call):
                    call_node = stmt.value.value

                if not call_node:
                    continue

                # Compare parameter names with forwarded call arguments
                param_names = [a.arg for a in node.args.args if a.arg != "self" and a.arg != "cls"]
                call_args = [ast.unparse(a) for a in call_node.args if isinstance(a, ast.Name)]

                if param_names and param_names == call_args and not call_node.keywords:
                    target_callee = ast.unparse(call_node.func)
                    wrappers.append({
                        "file": rel_path,
                        "wrapper": node.name,
                        "line": f"L{node.lineno}",
                        "forwards_to": target_callee,
                        "params": f"({', '.join(param_names)})",
                    })

        return wrappers

    @classmethod
    def format_audit_report(cls, root_dir: str) -> str:
        """Runs all 3 Phase-2 detectors and outputs a structured markdown audit."""
        clones = cls.find_duplicate_logic(root_dir)
        dead = cls.find_dead_exports(root_dir)
        wrappers = cls.find_useless_wrappers(root_dir)

        lines = [f"# Phase 2: Anti-AI-Slop & Clone Audit ({os.path.abspath(root_dir)})"]

        # Section 1: Clones
        lines.append(f"\n## 1. Structural Logic Clones ({len(clones)} groups found)")
        if not clones:
            lines.append("Clean: Zero structural function clones detected.")
        else:
            for c in clones:
                locs = ", ".join([f"`{x['file']}:{x['function']}` ({x['lines']})" for x in c["locations"]])
                lines.append(f"- **[Clone Hash `{c['fingerprint']}`]** ({c['count']}x): {locs}")

        # Section 2: Dead Exports
        total_dead = sum(len(v) for v in dead.values())
        lines.append(f"\n## 2. Unreferenced Cross-File Exports ({total_dead} symbols)")
        if not dead:
            lines.append("Clean: All exported public symbols are referenced externally.")
        else:
            for fpath, syms in dead.items():
                formatted = ", ".join([f"`{s['symbol']}` ({s['kind']} at {s['line']})" for s in syms])
                lines.append(f"- **`{fpath}`**: {formatted}")

        # Section 3: Pass-Through Wrappers
        lines.append(f"\n## 3. Hollow Pass-Through Wrappers ({len(wrappers)} detected)")
        if not wrappers:
            lines.append("Clean: Zero redundant pass-through wrapper functions.")
        else:
            for w in wrappers:
                lines.append(
                    f"- **`{w['file']}` ({w['line']})**: `{w['wrapper']}{w['params']}` "
                    f"blindly forwards to `{w['forwards_to']}{w['params']}`"
                )

        return "\n".join(lines)
